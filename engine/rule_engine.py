# RuleEngine
# ---------------------------------------------------------------------------

class RuleEngine:
    """Loads rules per domain, matches facts, resolves conflicts."""

    DOMAINS = ("liuyao", "ziwei", "bazi")
    RULES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rules")

    def __init__(self, rules_dir: Optional[str] = None):
        self.rules_dir = rules_dir or self.RULES_DIR
        self._cache: Dict[str, List[Dict[str, Any]]] = {}

    # ---------- loading ----------
    def load_rules(self, domain: str) -> List[Dict[str, Any]]:
        if domain not in self.DOMAINS:
            raise ValueError(f"unknown domain: {domain}; expected one of {self.DOMAINS}")
        if domain in self._cache:
            return self._cache[domain]
        path = os.path.join(self.rules_dir, f"rules_{domain}.json")
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        rules = data.get("rules", [])
        # pre-sort by priority desc for conflict resolution
        rules.sort(key=lambda r: (-r.get("priority", 5), -abs(r.get("weight", 0))))
        self._cache[domain] = rules
        return rules

    # ---------- matching ----------
    def match(self, input_data: Dict[str, Any], domain: str) -> Dict[str, Any]:
        rules = self.load_rules(domain)
        ev = ConditionEvaluator(input_data)

        matched: List[Dict[str, Any]] = []
        for r in rules:
            conds = r.get("conditions", [])
            if self._match_all(conds, ev):
                matched.append(r)

        # conflict resolution: same (domain, category) — highest priority wins,
        # lower priority same-category rules are dropped
        matched = self._resolve_conflicts(matched)

        # aggregate
        conclusions: List[str] = []
        total_weight = 0
        for r in matched:
            total_weight += r.get("weight", 0)
            for act in r.get("actions", []):
                conclusions.append(act.get("conclusion", ""))

        return {
            "matched_rules": [
                {
                    "rule_id": r["rule_id"],
                    "name": r["name"],
                    "category": r.get("category", ""),
                    "weight": r.get("weight", 0),
                    "priority": r.get("priority", 5),
                    "source": r.get("source", ""),
                    "detail": r.get("actions", [{}])[0].get("detail", ""),
                }
                for r in matched
            ],
            "conclusions": conclusions,
            "total_weight": total_weight,
            "matched_count": len(matched),
        }

    # ---------- internals ----------
    @staticmethod
    def _match_all(conds: List[Any], ev: ConditionEvaluator) -> bool:
        if not conds:
            return False
        for c in conds:
            if not ev.eval(c):
                return False
        return True

    @staticmethod
    def _resolve_conflicts(rules: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """
        Within the same (category), keep only the highest-priority rule when
        rules are mutually exclusive (negative weights with same conclusion
        sign conflict). Simplification: for each category, keep the highest
        priority rule only if its weight sign opposes others; otherwise keep all.
        """
        by_cat: Dict[str, List[Dict[str, Any]]] = {}
        for r in rules:
            cat = r.get("category", "")
            by_cat.setdefault(cat, []).append(r)

        out: List[Dict[str, Any]] = []
        for cat, rs in by_cat.items():
            rs.sort(key=lambda r: -r.get("priority", 5))
            top = rs[0]
            # always keep top; keep lower-priority only if they are not
            # explicitly opposed (i.e. same sign as top or zero weight)
            out.append(top)
            top_sign = (top.get("weight", 0) > 0) - (top.get("weight", 0) < 0)
            for r in rs[1:]:
                w = r.get("weight", 0)
                sign = (w > 0) - (w < 0)
                if sign == top_sign or w == 0:
                    out.append(r)
                # else: opposed sign with lower priority -> dropped
        # restore priority ordering
        out.sort(key=lambda r: (-r.get("priority", 5), r["rule_id"]))
        return out

    # ---------- listing ----------
    def list_rules(self, domain: str) -> Dict[str, Any]:
        rules = self.load_rules(domain)
        return {
            "domain": domain,
            "count": len(rules),
            "rules": [
                {
                    "rule_id": r["rule_id"],
                    "name": r["name"],
                    "category": r.get("category", ""),
                    "weight": r.get("weight", 0),
                    "priority": r.get("priority", 5),
                    "source": r.get("source", ""),
                }
                for r in rules
            ],
        }


