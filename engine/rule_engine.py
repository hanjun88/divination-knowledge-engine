"""
Rule Engine for Divination DSL.

Loads compiled rule JSON (per domain), evaluates AND/OR-nested conditions
against input facts, applies conflict resolution by priority/weight, and
returns matched rules + aggregated conclusions.

Operators supported:
  - Comparators: ==, !=, >=, <=, >, <, in, not_in, contains, contains_all,
                 contains_any, starts_with, ends_with
  - Wuxing relational: wuxing_sheng, wuxing_ke, wuxing_bihe, wuxing_tongqi,
                       liuchong, liuhe, yue_mu, ri_mu, yue_jue, ri_jue
  - Logical nesting: {"AND": [...]} / {"OR": [...]}
  - Template placeholders: "${month_zh}" resolved from input data.
"""
