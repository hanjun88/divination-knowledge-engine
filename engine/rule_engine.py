# ---------------------------------------------------------------------------
# Template resolver
# ---------------------------------------------------------------------------

def _resolve_template(value: Any, facts: Dict[str, Any]) -> Any:
    """Resolve ${path} placeholders against facts (dot-path access)."""
    if isinstance(value, str):
        if value.startswith("${") and value.endswith("}"):
            path = value[2:-1]
            return _get_path(facts, path)
        # mixed string with embedded placeholders
        if "${" in value:
            out = value
            for k in sorted(_extract_paths(value), key=len, reverse=True):
                out = out.replace("${" + k + "}", str(_get_path(facts, k)))
            return out
        return value
    return value


def _extract_paths(s: str) -> List[str]:
    import re
    return re.findall(r"\$\{([^}]+)\}", s)


def _get_path(obj: Any, path: str) -> Any:
    cur = obj
    for part in path.split("."):
        if isinstance(cur, dict):
            cur = cur.get(part)
        else:
            return None
    return cur


# ---------------------------------------------------------------------------
# Condition evaluator
# ---------------------------------------------------------------------------

class ConditionEvaluator:
    """Evaluate a single condition dict against facts."""

    def __init__(self, facts: Dict[str, Any]):
        self.facts = facts

    def eval(self, cond: Any) -> bool:
        if not isinstance(cond, dict):
            return bool(cond)
        # logical wrappers — support both {"AND": [...]} and
        # {"field": "AND", "conditions": [...]} forms
        if "AND" in cond and isinstance(cond["AND"], list):
            return all(self.eval(c) for c in cond["AND"])
        if "OR" in cond and isinstance(cond["OR"], list):
            return any(self.eval(c) for c in cond["OR"])
        if "NOT" in cond:
            return not self.eval(cond["NOT"])
        field_val = cond.get("field")
        if field_val in ("AND", "OR", "NOT") and "conditions" in cond:
            sub = cond["conditions"]
            if field_val == "AND":
                return all(self.eval(c) for c in sub)
            if field_val == "OR":
                return any(self.eval(c) for c in sub)
            if field_val == "NOT":
                return not self.eval(sub)
        # atomic condition
        return self._eval_atom(cond)

    def _eval_atom(self, cond: Dict[str, Any]) -> bool:
        op = cond.get("operator", "==")
        field = cond.get("field")
        actual = _resolve_template(field, self.facts) if isinstance(field, str) and "${" in field \
            else _get_path(self.facts, field or "")
        expected = cond.get("value")
        expected = _resolve_template(expected, self.facts) if isinstance(expected, str) else expected

        # wuxing relational operators: support both
        #   {"operator": "wuxing_ke", "left":..., "right":...}
        #   {"field": "wuxing_ke", "operator": "==", "left":..., "right":...}
        rel_ops = ("wuxing_sheng", "wuxing_ke", "wuxing_bihe", "wuxing_tongqi",
                   "liuchong", "liuhe")
        if op in rel_ops or (op == "==" and field in rel_ops):
            actual_op = op if op in rel_ops else field
            left = _resolve_template(cond.get("left"), self.facts)
            right = _resolve_template(cond.get("right"), self.facts)
            return self._eval_rel(actual_op, left, right)

        # tomb/jue lookup (one-arg with zhi + anchor)
        tomb_ops = ("yue_mu", "ri_mu", "yue_jue", "ri_jue")
        if op in tomb_ops or (op == "==" and field in tomb_ops):
            actual_op = op if op in tomb_ops else field
            zhi = _resolve_template(cond.get("zhi"), self.facts)
            anchor = _resolve_template(cond.get("month") or cond.get("day"), self.facts)
            wx = zhi_wx(zhi or "")
            if not wx or not anchor:
                return False
            anchor_wx = zhi_wx(anchor)
            if actual_op in ("yue_mu", "ri_mu"):
                return is_mu(wx, anchor) or is_mu(anchor_wx or "", zhi or "")
            if actual_op in ("yue_jue", "ri_jue"):
                return is_jue(wx, anchor) or is_jue(anchor_wx or "", zhi or "")
            return False

        # generic comparator
        try:
            if op == "==":
                return actual == expected
            if op == "!=":
                return actual != expected
            if op == ">=":
                return _num(actual) >= _num(expected)
            if op == "<=":
                return _num(actual) <= _num(expected)
            if op == ">":
                return _num(actual) > _num(expected)
            if op == "<":
                return _num(actual) < _num(expected)
            if op == "in":
                return actual in (expected or [])
            if op == "not_in":
                return actual not in (expected or [])
            if op == "contains":
                if isinstance(actual, (list, tuple, set)):
                    return expected in actual
                return expected in (actual or "")
            if op == "contains_all":
                if not isinstance(actual, (list, tuple, set)):
                    return False
                return all(v in actual for v in (expected or []))
            if op == "contains_any":
                if not isinstance(actual, (list, tuple, set)):
                    return False
                return any(v in actual for v in (expected or []))
            if op == "starts_with":
                return str(actual or "").startswith(str(expected))
            if op == "ends_with":
                return str(actual or "").endswith(str(expected))
            if op == "true":
                return bool(actual)
        except Exception:
            return False
        return False

    def _eval_rel(self, op: str, left: Any, right: Any) -> bool:
        if left is None or right is None:
            return False
        # wuxing operators
        if op == "wuxing_sheng":
            # left wx generates right wx? (e.g. 木 -> 火)
            return wuxing_sheng(left) == right
        if op == "wuxing_ke":
            return wuxing_ke(left) == right
        if op == "wuxing_bihe":
            return zhi_wx(left) == zhi_wx(right) and left != right
        if op == "wuxing_tongqi":
            # same qi: 寅 vs 卯 (both wood branch) etc — treat as same wx
            return zhi_wx(left) == zhi_wx(right)
        if op == "liuchong":
            return is_liuchong(left, right)
        if op == "liuhe":
            return is_liuhe(left, right)
        return False


def _num(x: Any) -> float:
    try:
        return float(x)
    except (TypeError, ValueError):
        return 0.0


