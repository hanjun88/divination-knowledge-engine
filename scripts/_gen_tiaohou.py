def build_rules():
    rules = []
    for gi, (g_char, g_full) in enumerate(GANS):
        for zi, z_char in enumerate(ZHIS):
            primary, secondary, detail = MATRIX[gi][zi]
            rule_id = f"BZ-TH-{gi + 1:02d}{zi + 1:02d}"
            name = f"{g_full}{z_char}月调候"
            if secondary:
                conclusion = f"调候用神: {primary}为主，{secondary}为辅"
            else:
                conclusion = f"调候用神: 专取{primary}"
            rules.append({
                "rule_id": rule_id,
                "domain": "bazi",
                "category": "tiaohou",
                "name": name,
                "conditions": [
                    {"field": "day_gan", "operator": "==", "value": g_char},
                    {"field": "month_zhi", "operator": "==", "value": z_char},
                ],
                "actions": [
                    {"conclusion": conclusion, "detail": detail}
                ],
                "weight": 5,
                "priority": 9,
                "source": f"造化元钥·{g_full}篇",
            })
    return rules


def main():
    data = json.loads(RULES_PATH.read_text(encoding="utf-8"))
    existing = data["rules"]
    existing_ids = {r["rule_id"] for r in existing}
    new_rules = build_rules()
    # safety: no duplicate rule ids
    for r in new_rules:
        assert r["rule_id"] not in existing_ids, f"dup {r['rule_id']}"
    data["rules"] = existing + new_rules
    data["count"] = len(data["rules"])
    RULES_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"existing rules: {len(existing)}")
    print(f"appended: {len(new_rules)}")
    print(f"total count: {data['count']}")
    # sanity: 120 unique new ids
    new_ids = [r["rule_id"] for r in new_rules]
    assert len(set(new_ids)) == 120
    print("sample BZ-TH-0101:", new_rules[0]["conditions"], new_rules[0]["actions"][0]["conclusion"])
    # 癸水子月 = gan idx 9, zhi idx 10 -> position 9*12+10 = 118
    gz = new_rules[9 * 12 + 10]
    print("sample BZ-TH-1011:", gz["rule_id"], gz["conditions"], gz["actions"][0]["conclusion"])


if __name__ == "__main__":
    main()
